#[cfg(test)]
mod tests {
	extern crate std;

	use super::*;

	#[test]
	fn lut_matches_the_curve() {
		for i in 0..256usize {
			let expect = (65535.0 * (i as f64 / 255.0).powf(2.45)).round() as u16;
			assert_eq!(GAMMA_DECODE[i], expect, "entry {i}");
		}
	}

	#[test]
	fn endpoints_are_exact() {
		assert_eq!(decode(0), 0);
		assert_eq!(decode(255), 65535);
	}
}
